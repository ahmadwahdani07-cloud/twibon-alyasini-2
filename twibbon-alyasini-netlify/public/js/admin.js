(function() {
  const loginScreen = document.getElementById('loginScreen');
  const dashboardScreen = document.getElementById('dashboardScreen');
  const loginForm = document.getElementById('loginForm');
  const loginUsername = document.getElementById('loginUsername');
  const loginPassword = document.getElementById('loginPassword');
  const btnLogout = document.getElementById('btnLogout');
  const btnFillDemo = document.getElementById('btnFillDemo');

  // Stats elements
  const statTotalCampaigns = document.getElementById('statTotalCampaigns');
  const statTotalViews = document.getElementById('statTotalViews');
  const statTotalDownloads = document.getElementById('statTotalDownloads');
  const statConversion = document.getElementById('statConversion');
  const campaignsGrid = document.getElementById('campaignsGrid');

  // Modal elements
  const campaignModal = document.getElementById('campaignModal');
  const btnOpenCreateModal = document.getElementById('btnOpenCreateModal');
  const btnCloseModal = document.getElementById('btnCloseModal');
  const btnCancelModal = document.getElementById('btnCancelModal');
  const campaignForm = document.getElementById('campaignForm');
  const modalTitle = document.getElementById('modalTitle');
  const editCampaignId = document.getElementById('editCampaignId');
  const campTitle = document.getElementById('campTitle');
  const campSlug = document.getElementById('campSlug');
  const urlPreview = document.getElementById('urlPreview');
  const frameDropzone = document.getElementById('frameDropzone');
  const frameFileInput = document.getElementById('frameFileInput');
  const framePreviewArea = document.getElementById('framePreviewArea');
  const framePreviewImg = document.getElementById('framePreviewImg');
  const dropzoneText = document.getElementById('dropzoneText');
  const campDesc = document.getElementById('campDesc');
  const campCaption = document.getElementById('campCaption');
  const campHashtags = document.getElementById('campHashtags');
  const btnSaveCampaign = document.getElementById('btnSaveCampaign');

  // Toast
  const adminToast = document.getElementById('adminToast');
  const adminToastMsg = document.getElementById('adminToastMsg');

  let slugAutoGenerated = true;
  let allCampaigns = [];

  function showToast(msg) {
    adminToastMsg.textContent = msg;
    adminToast.classList.add('show');
    setTimeout(() => adminToast.classList.remove('show'), 2500);
  }

  // --- CHECK AUTH ---
  async function checkAuth() {
    try {
      const res = await fetch('/api/auth/me');
      const data = await res.json();
      if (data.authenticated) {
        showDashboard();
      } else {
        showLogin();
      }
    } catch {
      showLogin();
    }
  }

  function showLogin() {
    loginScreen.style.display = 'flex';
    dashboardScreen.style.display = 'none';
  }

  function showDashboard() {
    loginScreen.style.display = 'none';
    dashboardScreen.style.display = 'flex';
    loadDashboardData();
  }

  // Demo auto-fill
  if (btnFillDemo) {
    btnFillDemo.addEventListener('click', () => {
      loginUsername.value = 'admin';
      loginPassword.value = 'alyasini2026';
    });
  }

  // Handle Login
  loginForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    const btn = document.getElementById('btnLoginSubmit');
    btn.textContent = 'Memverifikasi...';
    btn.disabled = true;

    try {
      const res = await fetch('/api/auth/login', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          username: loginUsername.value.trim(),
          password: loginPassword.value
        })
      });
      const data = await res.json();
      if (res.ok && data.success) {
        showToast('Berhasil masuk ke dapur twibbon!');
        showDashboard();
      } else {
        alert(data.error || 'Username atau password salah.');
      }
    } catch (err) {
      alert('Gagal menghubungi server: ' + err.message);
    } finally {
      btn.textContent = 'Masuk ke Dapur Twibbon';
      btn.disabled = false;
    }
  });

  // Handle Logout
  btnLogout.addEventListener('click', async () => {
    if (confirm('Apakah Anda yakin ingin keluar?')) {
      await fetch('/api/auth/logout', { method: 'POST' });
      showLogin();
    }
  });

  // --- DASHBOARD DATA ---
  async function loadDashboardData() {
    try {
      const res = await fetch('/api/stats');
      if (!res.ok) {
        if (res.status === 401) return showLogin();
        throw new Error('Gagal memuat statistik');
      }
      const data = await res.json();

      statTotalCampaigns.textContent = data.totalCampaigns || 0;
      statTotalViews.textContent = (data.totalViews || 0).toLocaleString();
      statTotalDownloads.textContent = (data.totalDownloads || 0).toLocaleString();
      statConversion.textContent = `${data.conversionRate || 0}%`;

      allCampaigns = data.campaigns || [];
      renderCampaignsGrid(allCampaigns);
    } catch (err) {
      console.error(err);
      campaignsGrid.innerHTML = `<p style="color: #ef4444; padding: 2rem;">Gagal memuat data: ${err.message}</p>`;
    }
  }

  function renderCampaignsGrid(campaigns) {
    if (!campaigns || campaigns.length === 0) {
      campaignsGrid.innerHTML = `
        <div style="grid-column: 1/-1; text-align: center; padding: 3rem; background: #fff; border-radius: 16px; border: 1px dashed #cbd5e1;">
          <p style="color: #64748b; font-size: 1.1rem; margin-bottom: 1rem;">Belum ada kampanye twibbon yang dibuat.</p>
          <button class="btn-create-campaign" onclick="document.getElementById('btnOpenCreateModal').click()">➕ Buat Kampanye Pertama</button>
        </div>
      `;
      return;
    }

    const origin = window.location.origin;

    campaignsGrid.innerHTML = campaigns.map(c => {
      const publicUrl = `${origin}/${c.slug}`;
      return `
        <div class="camp-card">
          <div class="camp-frame-preview-box">
            <img src="${c.frame_path}" alt="${c.title}" class="camp-frame-img">
            <span class="camp-badge-status">${c.is_active ? '● Aktif' : 'Nonaktif'}</span>
          </div>

          <div class="camp-card-body">
            <h3 class="camp-card-title">${escapeHtml(c.title)}</h3>
            <div class="camp-slug-tag">/${escapeHtml(c.slug)}</div>

            <div class="camp-card-stats">
              <div class="camp-stat-col">
                <div class="camp-stat-num">${(c.view_count || 0).toLocaleString()}</div>
                <div class="camp-stat-label">Tayangan (Views)</div>
              </div>
              <div class="camp-stat-col">
                <div class="camp-stat-num">${(c.download_count || 0).toLocaleString()}</div>
                <div class="camp-stat-label">Unduhan Siap Pakai</div>
              </div>
            </div>

            <div class="camp-card-actions">
              <a href="${publicUrl}" target="_blank" class="btn-card-action" title="Buka Halaman Publik">
                🔗 Buka Web
              </a>
              <button type="button" class="btn-card-action btn-copy" onclick="copyCampaignUrl('${publicUrl}')" title="Salin Link Acara">
                📋 Salin Link
              </button>
              <button type="button" class="btn-card-action" onclick="openEditCampaign(${c.id})" title="Edit Kampanye">
                ✏️ Edit
              </button>
              <button type="button" class="btn-card-action" style="color: #ef4444;" onclick="deleteCampaign(${c.id}, '${escapeHtml(c.title)}')" title="Hapus">
                🗑️
              </button>
            </div>
          </div>
        </div>
      `;
    }).join('');
  }

  function escapeHtml(str) {
    if (!str) return '';
    return str.replace(/[&<>'"]/g, 
      tag => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', "'": '&#39;', '"': '&quot;' }[tag] || tag)
    );
  }

  window.copyCampaignUrl = function(url) {
    navigator.clipboard.writeText(url).then(() => {
      showToast('Tautan twibbon berhasil disalin!');
    }).catch(() => {
      prompt('Salin tautan twibbon berikut:', url);
    });
  };

  window.deleteCampaign = async function(id, title) {
    if (!confirm(`Hapus kampanye "${title}"?\nSemua statistik kunjungan dan unduhan juga akan terhapus.`)) {
      return;
    }
    try {
      const res = await fetch(`/api/campaigns/${id}`, { method: 'DELETE' });
      if (res.ok) {
        showToast('Kampanye berhasil dihapus');
        loadDashboardData();
      } else {
        alert('Gagal menghapus kampanye');
      }
    } catch (err) {
      alert('Error: ' + err.message);
    }
  };

  // --- MODAL & FORM LOGIC ---
  function openModal(isEdit = false) {
    campaignModal.classList.add('open');
    if (!isEdit) {
      modalTitle.textContent = 'Buat Kampanye Twibbon Baru';
      campaignForm.reset();
      editCampaignId.value = '';
      framePreviewArea.style.display = 'none';
      dropzoneText.style.display = 'block';
      frameFileInput.value = '';
      slugAutoGenerated = true;
      updateUrlPreview('');
    }
  }

  function closeModal() {
    campaignModal.classList.remove('open');
  }

  btnOpenCreateModal.addEventListener('click', () => openModal(false));
  btnCloseModal.addEventListener('click', closeModal);
  btnCancelModal.addEventListener('click', closeModal);

  // Auto slug generation from title
  campTitle.addEventListener('input', () => {
    if (slugAutoGenerated && !editCampaignId.value) {
      const slugVal = campTitle.value.toLowerCase()
        .replace(/[^a-z0-9\s-]/g, '')
        .trim()
        .replace(/\s+/g, '-');
      campSlug.value = slugVal;
      updateUrlPreview(slugVal);
    }
  });

  campSlug.addEventListener('input', () => {
    slugAutoGenerated = false;
    updateUrlPreview(campSlug.value);
  });

  function updateUrlPreview(slug) {
    const s = slug ? slug.trim() : 'nama-acara';
    urlPreview.textContent = `${window.location.origin}/${s}`;
  }

  // Dropzone file handling
  frameDropzone.addEventListener('click', () => frameFileInput.click());

  frameDropzone.addEventListener('dragover', (e) => {
    e.preventDefault();
    frameDropzone.style.borderColor = '#006d4e';
  });

  frameDropzone.addEventListener('dragleave', () => {
    frameDropzone.style.borderColor = '#cbd5e1';
  });

  frameDropzone.addEventListener('drop', (e) => {
    e.preventDefault();
    frameDropzone.style.borderColor = '#cbd5e1';
    if (e.dataTransfer.files && e.dataTransfer.files[0]) {
      handleFileSelected(e.dataTransfer.files[0]);
    }
  });

  frameFileInput.addEventListener('change', (e) => {
    if (e.target.files && e.target.files[0]) {
      handleFileSelected(e.target.files[0]);
    }
  });

  function handleFileSelected(file) {
    if (!file.type.includes('png') && !file.type.includes('svg')) {
      alert('Mohon pilih file desain berformat PNG dengan area transparan (atau SVG).');
      return;
    }
    const reader = new FileReader();
    reader.onload = (e) => {
      framePreviewImg.src = e.target.result;
      framePreviewArea.style.display = 'block';
      dropzoneText.style.display = 'none';
    };
    reader.readAsDataURL(file);
  }

  window.openEditCampaign = function(id) {
    const c = allCampaigns.find(item => item.id === id);
    if (!c) return;

    modalTitle.textContent = 'Edit Kampanye Twibbon';
    editCampaignId.value = c.id;
    campTitle.value = c.title || '';
    campSlug.value = c.slug || '';
    campDesc.value = c.description || '';
    campCaption.value = c.caption || '';
    campHashtags.value = c.hashtags || '';
    slugAutoGenerated = false;
    updateUrlPreview(c.slug);

    if (c.frame_path) {
      framePreviewImg.src = c.frame_path;
      framePreviewArea.style.display = 'block';
      dropzoneText.style.display = 'none';
    }

    openModal(true);
  };

  // Submit Campaign Form
  campaignForm.addEventListener('submit', async (e) => {
    e.preventDefault();
    btnSaveCampaign.disabled = true;
    btnSaveCampaign.textContent = 'Menyimpan...';

    const isEdit = !!editCampaignId.value;
    const formData = new FormData();
    formData.append('title', campTitle.value.trim());
    formData.append('slug', campSlug.value.trim());
    formData.append('description', campDesc.value.trim());
    formData.append('caption', campCaption.value.trim());
    formData.append('hashtags', campHashtags.value.trim());

    if (frameFileInput.files && frameFileInput.files[0]) {
      formData.append('frame', frameFileInput.files[0]);
    }

    try {
      let url = '/api/campaigns';
      let method = 'POST';

      if (isEdit) {
        url = `/api/campaigns/${editCampaignId.value}`;
        method = 'PUT';
      }

      const res = await fetch(url, {
        method,
        body: formData
      });

      const data = await res.json();
      if (res.ok && data.success) {
        showToast(isEdit ? 'Kampanye berhasil diperbarui!' : 'Kampanye baru berhasil dibuat!');
        closeModal();
        loadDashboardData();
      } else {
        alert(data.error || 'Terjadi kesalahan saat menyimpan kampanye.');
      }
    } catch (err) {
      alert('Gagal menghubungi server: ' + err.message);
    } finally {
      btnSaveCampaign.disabled = false;
      btnSaveCampaign.textContent = '💾 Simpan Kampanye';
    }
  });

  // --- PASSWORD CHANGE MODAL ---
  const passwordModal = document.getElementById('passwordModal');
  const btnOpenChangePassword = document.getElementById('btnOpenChangePassword');
  const btnClosePasswordModal = document.getElementById('btnClosePasswordModal');
  const btnCancelPasswordModal = document.getElementById('btnCancelPasswordModal');
  const passwordForm = document.getElementById('passwordForm');
  const currentPassword = document.getElementById('currentPassword');
  const newPassword = document.getElementById('newPassword');
  const confirmPassword = document.getElementById('confirmPassword');
  const btnSavePassword = document.getElementById('btnSavePassword');

  if (btnOpenChangePassword) {
    btnOpenChangePassword.addEventListener('click', () => {
      passwordForm.reset();
      passwordModal.classList.add('open');
    });
  }

  function closePasswordModal() {
    passwordModal.classList.remove('open');
  }

  if (btnClosePasswordModal) btnClosePasswordModal.addEventListener('click', closePasswordModal);
  if (btnCancelPasswordModal) btnCancelPasswordModal.addEventListener('click', closePasswordModal);

  if (passwordForm) {
    passwordForm.addEventListener('submit', async (e) => {
      e.preventDefault();
      if (newPassword.value !== confirmPassword.value) {
        alert('Konfirmasi password baru tidak cocok!');
        return;
      }
      if (newPassword.value.length < 6) {
        alert('Password baru minimal 6 karakter!');
        return;
      }

      btnSavePassword.disabled = true;
      btnSavePassword.textContent = 'Menyimpan...';

      try {
        const res = await fetch('/api/auth/change-password', {
          method: 'POST',
          headers: { 'Content-Type': 'application/json' },
          body: JSON.stringify({
            currentPassword: currentPassword.value,
            newPassword: newPassword.value
          })
        });
        const data = await res.json();
        if (res.ok && data.success) {
          showToast('Password admin berhasil diubah!');
          closePasswordModal();
        } else {
          alert(data.error || 'Gagal mengubah password');
        }
      } catch (err) {
        alert('Error: ' + err.message);
      } finally {
        btnSavePassword.disabled = false;
        btnSavePassword.textContent = 'Simpan Password';
      }
    });
  }

  // Init
  checkAuth();
})();
